#!/usr/bin/env python3
"""
Generate the constant ROM / parameter modules used by the RTL (rtl/gen/*.v).

All tables come from dvbs2_ref.py (ETSI EN 302 307-1). ROMs are emitted as plain
Verilog case statements so the project has no $readmemh path dependencies.

    python3 gen_rtl_roms.py            -> writes ../rtl/gen/*.v
"""
import os
import numpy as np
from dvbs2_ref import CODES, CODE_ID, MODCODS, LDPC_SHORT, NLDPC, rrc_taps, ldpc_qc_structure

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'rtl', 'gen')
RATES = list(CODES)                      # code_id order
COEF_BITS = 18
COEF_SCALE = 1 << 17
ROLLOFFS = [0.35, 0.25, 0.20]           # rolloff register 0/1/2

# per-code default normalisation factor (numerator over 8) for the min-sum decoder
ALPHA_DEFAULT = {'1/4': 6, '1/3': 6, '2/5': 6}   # others 7


def header(name, desc):
    return (f"// {name}.v -- GENERATED by python/gen_rtl_roms.py, do not edit.\n"
            f"// {desc}\n`timescale 1ns/1ps\n")


def w(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), 'w') as f:
        f.write(text)


def gen_code_params():
    s = header('dvbs2_code_params', 'code_id -> LDPC/BCH frame parameters (short FECFRAME).')
    s += """module dvbs2_code_params (
    input  wire [3:0]  code_id,
    output reg  [13:0] kbch,      // BCH information bits
    output reg  [13:0] kldpc,     // LDPC information bits (= Nbch)
    output reg  [5:0]  q,         // LDPC q parameter (= M/360)
    output reg  [5:0]  ngroups,   // Kldpc/360
    output reg  [2:0]  alpha      // default min-sum normalisation numerator (/8)
);
always @(*) begin
    case (code_id)
"""
    for cid, r in enumerate(RATES):
        kbch, k, q = CODES[r]
        a = ALPHA_DEFAULT.get(r, 7)
        s += f"    4'd{cid}: begin kbch = 14'd{kbch}; kldpc = 14'd{k}; q = 6'd{q}; ngroups = 6'd{k // 360}; alpha = 3'd{a}; end // {r}\n"
    s += """    default: begin kbch = 14'd7032; kldpc = 14'd7200; q = 6'd25; ngroups = 6'd20; alpha = 3'd7; end
    endcase
end
endmodule
"""
    w('dvbs2_code_params.v', s)


def gen_modcod_map():
    s = header('dvbs2_modcod_map', 'DVB-S2 MODCOD (5 bit) -> supported?, 8PSK?, code_id.')
    s += """module dvbs2_modcod_map (
    input  wire [4:0] modcod,
    output reg        valid,
    output reg        is_8psk,
    output reg  [3:0] code_id
);
always @(*) begin
    valid = 1'b1; is_8psk = 1'b0; code_id = 4'd3;
    case (modcod)
"""
    for mc, (mod, r) in sorted(MODCODS.items()):
        s += f"    5'd{mc}: begin is_8psk = 1'b{1 if mod == '8PSK' else 0}; code_id = 4'd{CODE_ID[r]}; end // {mod} {r}\n"
    s += """    default: valid = 1'b0;
    endcase
end
endmodule
"""
    w('dvbs2_modcod_map.v', s)


def gen_ldpc_enc_rom():
    """TX: accumulator addresses x for every (code, info group)."""
    xs, rowinfo, code_base = [], [], []
    for r in RATES:
        code_base.append(len(rowinfo))
        for row in LDPC_SHORT[r]:
            rowinfo.append((len(xs), len(row)))
            xs.extend(row)
    abits = int(np.ceil(np.log2(len(xs))))
    rbits = int(np.ceil(np.log2(len(rowinfo))))
    s = header('ldpc_enc_rom', 'TX LDPC encoder tables (EN 302 307-1 Annex C, short frames).')
    s += f"""// x ROM: {len(xs)} entries; rowinfo ROM: {len(rowinfo)} rows (start, count).
module ldpc_enc_xrom (
    input  wire              clk,
    input  wire [{abits - 1}:0]     addr,
    output reg  [13:0]       x
);
always @(posedge clk) begin
    case (addr)
"""
    for i, x in enumerate(xs):
        s += f"    {abits}'d{i}: x <= 14'd{x};\n"
    s += f"""    default: x <= 14'd0;
    endcase
end
endmodule

module ldpc_enc_rowrom (
    input  wire              clk,
    input  wire [3:0]        code_id,
    input  wire [5:0]        group,
    output reg  [{abits - 1}:0]     start,
    output reg  [3:0]        count
);
reg [{rbits - 1}:0] base;
always @(*) begin
    case (code_id)
"""
    for cid, b in enumerate(code_base):
        s += f"    4'd{cid}: base = {rbits}'d{b};\n"
    s += f"""    default: base = {rbits}'d0;
    endcase
end
wire [{rbits - 1}:0] ra = base + group;
always @(posedge clk) begin
    case (ra)
"""
    for i, (st, cnt) in enumerate(rowinfo):
        s += f"    {rbits}'d{i}: begin start <= {abits}'d{st}; count <= 4'd{cnt}; end\n"
    s += f"""    default: begin start <= {abits}'d0; count <= 4'd0; end
    endcase
end
endmodule
"""
    w('ldpc_enc_rom.v', s)
    return abits


def gen_ldpc_dec_rom():
    """RX: circulant list per layer.  Each entry: group(7) shift(9) dup8(2) dup4(2) special(1)."""
    ents, layinfo, code_lbase = [], [], []
    for r in RATES:
        kbch, k, q = CODES[r]
        G = k // 360
        code_lbase.append(len(layinfo))
        for li, lay in enumerate(ldpc_qc_structure(r)):
            layinfo.append((len(ents), len(lay)))
            seen8, seen4 = {}, {}
            for (g, sh) in lay:
                d8 = seen8.get((g, sh % 8), 0); seen8[(g, sh % 8)] = d8 + 1
                d4 = seen4.get((g, sh % 4), 0); seen4[(g, sh % 4)] = d4 + 1
                special = int(li == 0 and g == G + q - 1 and sh == 1)
                ents.append((g, sh, d8, d4, special))
    assert max(e[2] for e in ents) <= 3 and max(e[3] for e in ents) <= 3
    abits = int(np.ceil(np.log2(len(ents))))
    lbits = int(np.ceil(np.log2(len(layinfo))))
    maxdc = max(d for _, d in layinfo)
    s = header('ldpc_dec_rom', 'RX LDPC decoder schedule: circulants grouped per layer (check group).')
    s += f"""// {len(ents)} circulants, {len(layinfo)} layers, max layer degree {maxdc}
// entry = {{group[6:0], shift[8:0], dup8[1:0], dup4[1:0], special}}
module ldpc_dec_crom (
    input  wire [{abits - 1}:0]     addr,
    output reg  [20:0]       ent
);
always @(*) begin
    case (addr)
"""
    for i, (g, sh, d8, d4, sp) in enumerate(ents):
        v = (g << 14) | (sh << 5) | (d8 << 3) | (d4 << 1) | sp
        s += f"    {abits}'d{i}: ent = 21'h{v:06x};\n"
    s += f"""    default: ent = 21'h0;
    endcase
end
endmodule

module ldpc_dec_lrom (
    input  wire [3:0]        code_id,
    input  wire [5:0]        layer,
    output reg  [{abits - 1}:0]     start,
    output reg  [4:0]        dc
);
reg [{lbits - 1}:0] base;
always @(*) begin
    case (code_id)
"""
    for cid, b in enumerate(code_lbase):
        s += f"    4'd{cid}: base = {lbits}'d{b};\n"
    s += f"""    default: base = {lbits}'d0;
    endcase
end
wire [{lbits - 1}:0] la = base + layer;
always @(*) begin
    case (la)
"""
    for i, (st, d) in enumerate(layinfo):
        s += f"    {lbits}'d{i}: begin start = {abits}'d{st}; dc = 5'd{d}; end\n"
    s += f"""    default: begin start = {abits}'d0; dc = 5'd0; end
    endcase
end
endmodule
"""
    w('ldpc_dec_rom.v', s)
    return abits, maxdc


def gen_rrc_rom():
    s = header('rrc_coef_rom', 'RRC 33-tap (16 symbols @ 2 sps) half-filter coefficients, Q1.17.')
    s += """module rrc_coef_rom (
    input  wire [1:0]  rolloff,   // 0:0.35 1:0.25 2:0.20
    input  wire [4:0]  idx,       // 0..16 (16 = centre tap)
    output reg  signed [17:0] coef
);
always @(*) begin
    case ({rolloff, idx})
"""
    for ri, b in enumerate(ROLLOFFS):
        h = rrc_taps(b, 2, 16)
        for i in range(17):
            c = int(round(h[i] * COEF_SCALE))
            assert -(1 << 17) <= c < (1 << 17)
            neg = c < 0
            s += f"    {{2'd{ri}, 5'd{i}}}: coef = {'-' if neg else ''}18'sd{abs(c)};\n"
    s += """    default: coef = 18'sd0;
    endcase
end
endmodule
"""
    w('rrc_coef_rom.v', s)


if __name__ == '__main__':
    gen_code_params()
    gen_modcod_map()
    a = gen_ldpc_enc_rom()
    b = gen_ldpc_dec_rom()
    gen_rrc_rom()
    print('generated into', os.path.normpath(OUT), 'enc addr bits', a, 'dec (addr bits, maxdc)', b)


def gen_bch_poly():
    from dvbs2_ref import BCH_GEN_SHORT, BCH_PARITY
    g = BCH_GEN_SHORT & ((1 << BCH_PARITY) - 1)
    s = header('bch_gen_poly', 'DVB-S2 short-frame BCH generator g(x)=g1..g12 (degree 168), x^0..x^167.')
    s += "module bch_gen_poly (output wire [167:0] g);\nassign g = 168'h%042x;\nendmodule\n" % g
    w('bch_gen_poly.v', s)


def gen_llr_init():
    """Decoder LLR loader: start position of the 8PSK column streams (bit 5400 / 10800)."""
    s = header('ldpc_llr_init', 'start (region, a, b) of codeword bit 5400*sel for the LLR loader.')
    s += """// region 0: info (a = group, b = position), region 1: parity (a = r, b = c), j = r + q*c
module ldpc_llr_init (
    input  wire [3:0] code_id,
    input  wire [1:0] sel,        // 0: bit 0, 1: bit 5400, 2: bit 10800
    output reg        par,
    output reg  [5:0] a,
    output reg  [8:0] b
);
always @(*) begin
    par = 1'b0; a = 6'd0; b = 9'd0;
    case ({code_id, sel})
"""
    for cid, r in enumerate(RATES):
        kbch, k, q = CODES[r]
        for sel in (1, 2):
            B = 5400 * sel
            if B < k:
                assert B % 360 == 0
                par, a, b = 0, B // 360, 0
            else:
                j0 = B - k
                par, a, b = 1, j0 % q, j0 // q
            s += f"    {{4'd{cid}, 2'd{sel}}}: begin par = 1'b{par}; a = 6'd{a}; b = 9'd{b}; end\n"
    s += """    default: ;
    endcase
end
endmodule
"""
    w('ldpc_llr_init.v', s)


if __name__ == '__main__':
    gen_bch_poly()
    gen_llr_init()


def gen_bch_chien_rom():
    """alpha^(-j*(n-1)) for j=1..12 and every code (n = Nbch = Kldpc)."""
    from dvbs2_ref import GF_EXP, GF_N
    s = header('bch_chien_rom', 'BCH Chien search start constants alpha^(-j*(Nbch-1)), j=1..12.')
    s += """module bch_chien_rom (
    input  wire [3:0]  code_id,
    input  wire [3:0]  j,
    output reg  [13:0] c
);
always @(*) begin
    c = 14'd1;
    case ({code_id, j})
"""
    for cid, r in enumerate(RATES):
        kbch, k, q = CODES[r]
        for j in range(1, 13):
            v = int(GF_EXP[(-j * (k - 1)) % GF_N])
            s += f"    {{4'd{cid}, 4'd{j}}}: c = 14'h{v:04x};\n"
    s += """    default: ;
    endcase
end
endmodule
"""
    w('bch_chien_rom.v', s)


if __name__ == '__main__':
    gen_bch_chien_rom()


def gen_interp_rom():
    """Channel emulator fractional-delay interpolator: 64 phases x 8 taps, Q1.14.
    Phase p (f = p/64) tap j multiplies window sample j (j=3 is floor(t))."""
    import numpy as np
    L = 4
    s = header('ch_interp_rom', 'Kaiser-windowed sinc, 8 taps x 64 phases, Q1.14.')
    s += """module ch_interp_rom (
    input  wire [5:0] phase,
    input  wire [2:0] tap,
    output reg  signed [15:0] c
);
always @(*) begin
    case ({phase, tap})
"""
    for p in range(64):
        f = p / 64
        x = f - (np.arange(8) - 3)
        h = np.sinc(x) * np.kaiser(1001, 6.0)[np.clip(np.round((x + L) / (2 * L) * 1000).astype(int), 0, 1000)]
        h = h / h.sum()
        for j in range(8):
            v = int(round(h[j] * 16384))
            s += f"    {{6'd{p}, 3'd{j}}}: c = {'-' if v < 0 else ''}16'sd{abs(v)};\n"
    s += """    default: c = 16'sd0;
    endcase
end
endmodule
"""
    w('ch_interp_rom.v', s)


if __name__ == '__main__':
    gen_interp_rom()


def gen_pilot_gold_rom():
    """Gold scrambling indices R_n of the 36-symbol pilot blocks j=0..4 (body index
    1440 + 1476*j + m), for the RX pilot correlators."""
    from dvbs2_ref import pl_scrambler_rn
    g = pl_scrambler_rn(8370)
    s = header('pilot_gold_rom', 'PL scrambler R_n at pilot block positions (body index 1440+1476j+m).')
    s += """module pilot_gold_rom (
    input  wire [2:0] blk,
    input  wire [5:0] m,
    output reg  [1:0] r
);
always @(*) begin
    r = 2'd0;
    case ({blk, m})
"""
    for j in range(5):
        for m in range(36):
            s += f"    {{3'd{j}, 6'd{m}}}: r = 2'd{int(g[1440 + 1476 * j + m])};\n"
    s += """    default: ;
    endcase
end
endmodule
"""
    w('pilot_gold_rom.v', s)


if __name__ == '__main__':
    gen_pilot_gold_rom()
