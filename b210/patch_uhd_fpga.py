#!/usr/bin/env python3
"""
patch_uhd_fpga.py -- add the DVB-S2 modem to the USRP B210 FPGA image of a UHD source tree.

    python3 patch_uhd_fpga.py <uhd source root>        (e.g. ~/uhd, a checkout of the
                                                         tag matching your installed UHD)

What it does (idempotent; the original files are kept as *.orig):
  * copies the DVB-S2 RTL to  fpga/usrp3/lib/dvbs2/  (+ Makefile.srcs)
  * fpga/usrp3/lib/radio_200/radio_legacy.v
      - new parameter DVBS2 (default 0)
      - DUC input and DDC output routed through dvbs2_b210 when DVBS2 = 1
      - its own user-settings bus + readback (UHD "enable_user_regs" interface)
  * fpga/usrp3/top/b200/b200_core.v   radio_0 gets DVBS2 = 1 when `DVBS2 is defined
  * fpga/usrp3/top/b200/Makefile(.b200.inc)  new target  B210_DVBS2
Then:   cd <uhd>/fpga/usrp3/top/b200 && make B210_DVBS2
Result: build/usrp_b210_dvbs2_fpga.bin
"""
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))

RTL = {
    'common': ['ram_sdp.v', 'fir_sym33.v', 'cordic.v', 'sample_pacer.v'],
    'gen': ['dvbs2_code_params.v', 'dvbs2_modcod_map.v', 'ldpc_enc_rom.v', 'ldpc_dec_rom.v',
            'ldpc_llr_init.v', 'bch_gen_poly.v', 'bch_chien_rom.v', 'rrc_coef_rom.v', 'pilot_gold_rom.v'],
    'tx': None,          # all files
    'rx': None,
    'b210': None,
}
MARK = 'DVBS2-PATCH'


def die(msg):
    sys.exit('ERROR: ' + msg)


def backup(path):
    """Keep the pristine file as *.orig.  If the current file has no patch marker
    (e.g. the tree was updated / checked out again), it is the new pristine version."""
    with open(path) as f:
        patched = MARK in f.read()
    if not patched or not os.path.exists(path + '.orig'):
        if patched:
            die('%s is already patched but %s.orig is missing; restore it with git checkout' % (path, path))
        shutil.copy2(path, path + '.orig')


def read_orig(path):
    """Always patch from the pristine file (idempotent re-runs)."""
    backup(path)
    with open(path + '.orig') as f:
        return f.read()


def write(path, text):
    with open(path, 'w') as f:
        f.write(text)
    print('  patched', os.path.relpath(path))


def sub_once(text, pattern, repl, what, flags=0):
    new, n = re.subn(pattern, repl, text, count=1, flags=flags)
    if n != 1:
        die('anchor not found in %s: %s' % (what, pattern))
    return new


def copy_rtl(fpga):
    dst = os.path.join(fpga, 'usrp3', 'lib', 'dvbs2')
    os.makedirs(dst, exist_ok=True)
    files = []
    for sub, names in RTL.items():
        src = os.path.join(ROOT, 'rtl', sub)
        if names is None:
            names = sorted(f for f in os.listdir(src) if f.endswith('.v'))
        for n in names:
            shutil.copy2(os.path.join(src, n), os.path.join(dst, n))
            files.append(n)
    with open(os.path.join(dst, 'Makefile.srcs'), 'w') as f:
        f.write('#\n# DVB-S2 modem (generated by patch_uhd_fpga.py)\n#\n')
        f.write('DVBS2_SRCS = $(abspath $(addprefix $(BASE_DIR)/../lib/dvbs2/, \\\n')
        for n in files:
            f.write('%s \\\n' % n)
        f.write('))\n')
    print('  copied %d RTL files to %s' % (len(files), os.path.relpath(dst)))


def patch_radio(fpga):
    path = os.path.join(fpga, 'usrp3', 'lib', 'radio_200', 'radio_legacy.v')
    t = read_orig(path)
    # parameter
    t = sub_once(t, r'(\n(\s*)parameter USER_SETTINGS\s*=\s*0,)',
                 r'\1\n\2parameter DVBS2 = 0,    // ' + MARK + ': DVB-S2 modem between host and DUC/DDC',
                 'radio_legacy parameters')
    # declarations right after rb_data_user
    t = sub_once(t, r'(\n\s*reg\s*\[63:0\]\s*rb_data_user;)',
                 r'\1\n   // ' + MARK + '\n   wire [63:0] rb_data_dvbs2;\n'
                 '   wire [31:0] sample_tx_duc;   // sample fed to the DUC\n'
                 '   wire [31:0] sample_rx_ddc;   // sample produced by the DDC',
                 'rb_data_user declaration')
    # readback mux
    t = sub_once(t, r'3\'d7\s*:\s*rb_data\s*<=\s*rb_data_user;',
                 "3'd7 : rb_data <= (DVBS2 != 0) ? rb_data_dvbs2 : rb_data_user;  // " + MARK,
                 'readback case 7')
    # DUC input (only inside the duc_chain instance)
    m = re.search(r'duc_chain\s*#\(.*?\)\s*duc_chain\s*\((.*?)\);', t, re.S)
    if not m:
        die('duc_chain instance not found')
    inst = m.group(0)
    new = re.sub(r'\.sample\(\s*sample_tx\s*\)', '.sample(sample_tx_duc)', inst)
    if new == inst:
        die('.sample(sample_tx) not found in duc_chain')
    t = t.replace(inst, new)
    # DDC output (only inside the ddc_chain instance)
    m = re.search(r'ddc_chain\s*#\(.*?\)\s*ddc_chain\s*\((.*?)\);', t, re.S)
    if not m:
        die('ddc_chain instance not found')
    inst = m.group(0)
    new = re.sub(r'\.sample\(\s*sample_rx\s*\)', '.sample(sample_rx_ddc)', inst)
    if new == inst:
        die('.sample(sample_rx) not found in ddc_chain')
    t = t.replace(inst, new)
    # the modem itself, at the end of the module
    block = r'''
   // ////////////////////////////////////////////////////////////////////////////
   // %s: DVB-S2 modem (rtl/b210/dvbs2_b210.v) between the host streams and DUC/DDC
   generate
   if (DVBS2 != 0) begin : g_dvbs2
      wire           dv_set_stb;
      wire [7:0]     dv_set_addr;
      wire [31:0]    dv_set_data;
      wire [7:0]     dv_rb_addr;
      user_settings #(.BASE(SR_USER_SR_BASE)) dv_user_settings
        (.clk(radio_clk), .rst(radio_rst),
         .set_stb(set_stb), .set_addr(set_addr), .set_data(set_data),
         .set_stb_user(dv_set_stb), .set_addr_user(dv_set_addr), .set_data_user(dv_set_data));
      setting_reg #(.my_addr(SR_USER_RB_ADDR), .awidth(8), .width(8)) dv_rb_addr_reg
        (.clk(radio_clk), .rst(radio_rst), .strobe(set_stb), .addr(set_addr), .in(set_data),
         .out(dv_rb_addr), .changed());
      dvbs2_b210 #(.LDPC_P(45)) dvbs2
        (.clk(radio_clk), .rst(radio_rst),
         .set_stb(dv_set_stb), .set_addr(dv_set_addr), .set_data(dv_set_data),
         .rb_addr(dv_rb_addr), .rb_data(rb_data_dvbs2),
         .tx_host_sample(sample_tx), .tx_strobe(strobe_tx), .tx_run(run_tx), .tx_duc_sample(sample_tx_duc),
         .rx_ddc_sample(sample_rx_ddc), .rx_strobe(strobe_rx), .rx_run(run_rx), .rx_host_sample(sample_rx));
   end else begin : g_no_dvbs2
      assign sample_tx_duc = sample_tx;
      assign sample_rx     = sample_rx_ddc;
      assign rb_data_dvbs2 = 64'd0;
   end
   endgenerate
''' % MARK
    t = sub_once(t, r'(\n\s*/\*{10,}\s*\n\s*\* Debug only logic)', block.replace('\\', '\\\\') + r'\1',
                 'debug section of radio_legacy')
    write(path, t)


def patch_core(fpga):
    path = os.path.join(fpga, 'usrp3', 'top', 'b200', 'b200_core.v')
    t = read_orig(path)
    # first radio_legacy instance = radio_0
    t = sub_once(t, r'(\n(\s*)radio_legacy\s*#\()',
                 '\n`ifdef DVBS2\n   localparam DVBS2_R0 = 1;   // ' + MARK + '\n`else\n   localparam DVBS2_R0 = 0;\n`endif'
                 r'\1', 'radio_0 instance')
    t = sub_once(t, r'(radio_legacy\s*#\((?:(?!radio_legacy).)*?\.USER_SETTINGS\(0\),)',
                 r'\1\n      .DVBS2(DVBS2_R0),', 'radio_0 USER_SETTINGS', flags=re.S)
    write(path, t)


def patch_make(fpga):
    top = os.path.join(fpga, 'usrp3', 'top', 'b200')
    path = os.path.join(top, 'Makefile.b200.inc')
    t = read_orig(path)
    t = sub_once(t, r'(include \.\./\.\./lib/radio_200/Makefile\.srcs)',
                 r'\1\ninclude ../../lib/dvbs2/Makefile.srcs  # ' + MARK, 'radio_200 include')
    t = sub_once(t, r'(\$\(RADIO_200_SRCS\) \\)', r'\1\n$(if $(findstring DVBS2,$(NAME)),$(DVBS2_SRCS)) \\', 'SOURCES list')
    t = sub_once(t, r'ifeq \(\$\(NAME\),B210\)', 'ifneq (,$(filter B210%,$(NAME)))', 'gpio.ucf condition')
    write(path, t)
    path = os.path.join(top, 'Makefile')
    t = read_orig(path)
    target = ('# ' + MARK + '\n'
              'B210_DVBS2:  ##Build USRP B210 design with the DVB-S2 modem in radio 0.\n'
              '\t$(call pre_build,B210_DVBS2)\n'
              '\t$(call ise_build,XC6SLX150,TARGET_B210=1 DVBS2=1 DVBS2_FIR_FOLD=1 SYNTHESIS=1)\n'
              '\t$(call post_build,B210_DVBS2)\n\n')
    t = sub_once(t, r'(\nclean:)', '\n' + target.replace('\\', '\\\\') + r'\1', 'clean target')
    write(path, t)


def main():
    if len(sys.argv) != 2:
        die('usage: patch_uhd_fpga.py <uhd source root>')
    uhd = os.path.abspath(sys.argv[1])
    fpga = os.path.join(uhd, 'fpga')
    if not os.path.isfile(os.path.join(fpga, 'usrp3', 'lib', 'radio_200', 'radio_legacy.v')):
        die('%s does not look like a UHD source tree (fpga/usrp3/lib/radio_200/radio_legacy.v missing)' % uhd)
    print('patching', uhd)
    copy_rtl(fpga)
    patch_radio(fpga)
    patch_core(fpga)
    patch_make(fpga)
    print('done.  Build with:  cd %s && make B210_DVBS2' % os.path.join(fpga, 'usrp3', 'top', 'b200'))


if __name__ == '__main__':
    main()
